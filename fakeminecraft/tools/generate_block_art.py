"""Generate original block art from the official Bedrock identifier catalog."""
import hashlib
import json
import math
import re
import urllib.request
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SOURCE = "https://raw.githubusercontent.com/Mojang/bedrock-samples/v1.26.50.4/resource_pack/blocks.json"
LISTING = "https://learn.microsoft.com/en-us/minecraft/creator/reference/content/vanillalistingsreference/blocks?view=minecraft-bedrock-stable"
FIRST = ["grass", "dirt", "stone", "sand", "oak_log", "oak_leaves"]
PALETTES = [
    ((80, 139, 56), (48, 100, 39), "organic", ("grass", "moss", "leaf", "leaves", "vine", "sapling")),
    ((132, 89, 55), (90, 56, 37), "grain", ("wood", "log", "planks", "bamboo", "stem", "hyphae")),
    ((126, 130, 133), (75, 80, 84), "stone", ("stone", "cobble", "deepslate", "andesite", "diorite", "granite", "tuff", "basalt")),
    ((125, 88, 56), (84, 56, 34), "stone", ("dirt", "mud")),
    ((191, 163, 103), (138, 103, 65), "grain", ("sand", "sandstone", "clay")),
    ((87, 125, 150), (44, 81, 118), "crystal", ("ice", "water", "prismarine", "diamond")),
    ((156, 88, 72), (99, 46, 45), "brick", ("brick", "nether", "red", "terracotta")),
    ((170, 168, 160), (105, 104, 101), "stone", ("iron", "quartz", "calcite", "white")),
]


def art(name):
    digest = hashlib.blake2s(name.encode(), digest_size=32).digest()
    base, dark, pattern = (116, 116, 116), (67, 67, 67), "stone"
    for light, shade, style, words in PALETTES:
        if any(word in name for word in words):
            base, dark, pattern = light, shade, style
            break
    if "glass" in name:
        pattern = "crystal"
    tint = tuple((base[i] + digest[i] % 37 - 18) for i in range(3))
    image = Image.new("RGBA", (16, 16))
    pixels = image.load()
    for y in range(16):
        for x in range(16):
            h = hashlib.blake2s(f"{name}:{x//2}:{y//2}".encode(), digest_size=4).digest()
            noise = h[0] % 35 - 17
            if pattern == "grain":
                noise += 15 if x % 5 == digest[4] % 5 else -4
            elif pattern == "brick":
                seam = y % 5 == 0 or (x + (y // 5 % 2) * 4) % 8 == 0
                noise -= 45 if seam else 0
            elif pattern == "crystal":
                noise += 28 if (x + y + digest[5]) % 7 == 0 else 0
            elif pattern == "organic":
                noise += 17 if (x * 3 + y * 5 + digest[6]) % 11 < 3 else 0
            else:
                noise += 11 if h[1] % 5 == 0 else 0
            color = tuple(max(0, min(255, (tint[i] + noise + dark[i]) // 2 if noise < -10 else tint[i] + noise)) for i in range(3))
            pixels[x, y] = (*color, 255)
    return image


def main():
    names = set(json.load(urllib.request.urlopen(SOURCE, timeout=30)))
    listing = urllib.request.urlopen(LISTING, timeout=30).read().decode()
    names.update(re.findall(r'<tr>\s*<td[^>]*>minecraft:([a-z0-9_]+)</td>', listing))
    ordered = FIRST + sorted(names - set(FIRST) - {"air"})
    out = ROOT / "assets"
    tiles = out / "blocks"
    tiles.mkdir(parents=True, exist_ok=True)
    Image.new("RGBA", (16, 16)).save(tiles / "air.png")
    width = 32
    atlas = Image.new("RGBA", (width * 16, math.ceil(len(ordered) / width) * 16))
    with (out / "blocks.tsv").open("w", encoding="utf-8") as manifest:
        manifest.write("id\tbedrock_identifier\ttexture\n")
        manifest.write("0\tminecraft:air\tblocks/air.png\n")
        for number, name in enumerate(ordered, 1):
            image = art(name)
            image.save(tiles / f"{name}.png")
            atlas.paste(image, (((number - 1) % width) * 16, ((number - 1) // width) * 16))
            manifest.write(f"{number}\tminecraft:{name}\tblocks/{name}.png\n")
    side = art("dirt")
    side.paste(art("grass").crop((0, 0, 16, 4)), (0, 0))
    side.save(out / "grass_side.png")
    side_tile = len(ordered)
    atlas.paste(side, ((side_tile % width) * 16, (side_tile // width) * 16))
    atlas.save(out / "block_atlas.png")
    (out / "block_atlas.rgba").write_bytes(atlas.tobytes())
    (out / "SOURCE.txt").write_text(
        "Identifiers derived from Mojang bedrock-samples v1.26.50.4 and Microsoft Learn.\n"
        "All PNG pixels were generated by tools/generate_block_art.py; no Minecraft textures are included.\n"
        f"Sources: {SOURCE}\n{LISTING}\n", encoding="utf-8")
    print(f"Generated {len(ordered)+1} original textures including air")


if __name__ == "__main__":
    main()
